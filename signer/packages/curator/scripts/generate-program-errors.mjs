#!/usr/bin/env node
/**
 * Regenerate `src/program-errors.generated.js` from the two Anchor error
 * enums the curator talks to.
 *
 * Anchor numbers `#[error_code]` variants 6000 + declaration index, so the
 * only thing that matters is the ORDER of the variants in the Rust source.
 * The table is embedded (not parsed at boot) because the signer runs in a
 * container that has no sibling checkout; the test re-parses the `.rs` when
 * one is present and fails when the embedded table has drifted, which is how
 * a program upgrade that inserts a variant mid-enum gets noticed before the
 * journal starts naming the wrong error.
 *
 *   node scripts/generate-program-errors.mjs [--umbrella <dir>] [--check]
 *
 * `--umbrella` defaults to `$COMPOSABLE_PORTFOLIOS_UMBRELLA`; the Rust
 * sources are in weavr's private program repos beside it, so without one the
 * generator refuses (exit 2) rather than guess a path. `--check` exits 1
 * instead of writing when the generated file is stale.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE = join(HERE, '..');
export const OUTPUT = join(PACKAGE, 'src', 'program-errors.generated.js');

/** Where each enum lives, relative to the umbrella root. */
export const SOURCES = Object.freeze({
  portfolio_factory: {
    path: 'composable-portfolios-programs/programs/portfolio_factory/src/errors.rs',
    enumName: 'FactoryError',
    constName: 'FACTORY_ERRORS',
  },
  stoken: {
    path: 'splyce-composable-core/programs/stoken/src/errors.rs',
    enumName: 'STokenError',
    constName: 'STOKEN_ERRORS',
  },
});

/** `--umbrella`, else `COMPOSABLE_PORTFOLIOS_UMBRELLA`, else null: never a guess. */
export function umbrellaRoot(explicit) {
  const named = explicit ?? process.env.COMPOSABLE_PORTFOLIOS_UMBRELLA;
  return named ? resolve(named) : null;
}

/**
 * The variant names of one `#[error_code] pub enum <name> { … }`, in
 * declaration order. Comments and `#[msg("…")]` attributes (which may span
 * lines and contain commas or braces) are stripped first so that only the
 * `Variant,` lines remain; anything else inside the body is a parse failure,
 * not a silently skipped variant.
 * @param {string} source Rust source text
 * @param {string} enumName
 * @returns {string[]}
 */
export function parseErrorEnum(source, enumName) {
  const withoutComments = source.replace(/\/\/[^\n]*/g, '');
  const start = withoutComments.search(new RegExp(`pub\\s+enum\\s+${enumName}\\s*\\{`));
  if (start < 0) throw new Error(`no \`pub enum ${enumName}\` in source`);
  const open = withoutComments.indexOf('{', start);
  // The attributes are the only place a brace can appear inside the body, so
  // strip them before looking for the closing one.
  const body = withoutComments.slice(open + 1).replace(/#\[msg\([\s\S]*?\)\]/g, '');
  const close = body.indexOf('}');
  if (close < 0) throw new Error(`unterminated enum ${enumName}`);
  const names = [];
  for (const raw of body.slice(0, close).split('\n')) {
    const line = raw.trim();
    if (line === '') continue;
    const match = /^([A-Z][A-Za-z0-9]*)\s*,?$/.exec(line);
    if (!match) throw new Error(`unexpected line in enum ${enumName}: ${line}`);
    names.push(match[1]);
  }
  if (names.length === 0) throw new Error(`enum ${enumName} has no variants`);
  if (new Set(names).size !== names.length) throw new Error(`enum ${enumName} repeats a variant`);
  return names;
}

/** Read and parse every source enum under `umbrella`. */
export function readErrorTables(umbrella) {
  const tables = {};
  for (const [program, spec] of Object.entries(SOURCES)) {
    const file = join(umbrella, spec.path);
    if (!existsSync(file)) throw new Error(`${program}: ${file} is missing`);
    tables[program] = parseErrorEnum(readFileSync(file, 'utf8'), spec.enumName);
  }
  return tables;
}

export function renderModule(tables) {
  const lines = [
    '/**',
    ' * GENERATED by scripts/generate-program-errors.mjs — do not edit.',
    ' *',
    ' * Anchor error names in enum declaration order; the on-chain code is',
    ' * 6000 + index. Regenerate after any change to the source enums and let',
    ' * test/errors.test.js prove the embedded copy matches the checkout.',
    ' */',
    '',
  ];
  for (const [program, spec] of Object.entries(SOURCES)) {
    const names = tables[program];
    lines.push(`/** ${spec.enumName} (${spec.path}): ${names.length} variants. */`);
    lines.push(`export const ${spec.constName} = Object.freeze([`);
    for (const name of names) lines.push(`  '${name}',`);
    lines.push(']);', '');
  }
  return `${lines.join('\n')}`;
}

function main(argv) {
  const check = argv.includes('--check');
  const at = argv.indexOf('--umbrella');
  const umbrella = umbrellaRoot(at >= 0 ? argv[at + 1] : undefined);
  if (!umbrella) {
    console.error('generate-program-errors: pass --umbrella <dir> or set COMPOSABLE_PORTFOLIOS_UMBRELLA (the Rust sources are in the program repos beside it)');
    return 2;
  }
  const rendered = renderModule(readErrorTables(umbrella));
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null;
  if (current === rendered) {
    console.log(`${OUTPUT} is up to date`);
    return 0;
  }
  if (check) {
    console.error(`${OUTPUT} is stale; run scripts/generate-program-errors.mjs`);
    return 1;
  }
  writeFileSync(OUTPUT, rendered);
  console.log(`wrote ${OUTPUT}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(`generate-program-errors: ${error.message}`);
    process.exit(1);
  }
}
